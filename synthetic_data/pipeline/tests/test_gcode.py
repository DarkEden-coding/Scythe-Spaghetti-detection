def test_unlabelled_and_legacy_object_fallback(tmp_path):
    import json
    t = parse(tmp_path, ";TYPE:Perimeter\nG1 X10 E1\nG1 X20 E1\n")
    assert t.objects == []
    np.testing.assert_array_equal(t.obj, [-1, -1])
    output = tmp_path / "legacy.npz"
    arrays = {k: v for k, v in vars(t).items() if isinstance(v, np.ndarray) and k != "obj"}
    meta = dict(t.meta)
    meta.pop("objects")
    np.savez(output, **arrays, meta=np.array(json.dumps(meta)))
    spec = importlib.util.spec_from_file_location("legacy_blender_reader", READER)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    for loader in [load_timeline, module.load_timeline]:
        old = loader(output)
        assert old.objects == []
        np.testing.assert_array_equal(old.obj, [-1, -1])
    compare_readers(t, tmp_path)


