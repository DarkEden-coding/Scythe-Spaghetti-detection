def compare_readers(t, tmp_path):
    output = tmp_path / "timeline.npz"
    save_timeline(t, output)
    reloaded = load_timeline(output)
    np.testing.assert_array_equal(t.t0, reloaded.t0)
    np.testing.assert_array_equal(t.obj, reloaded.obj)
    spec = importlib.util.spec_from_file_location("blender_timeline_reference", READER)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    other = module.load_timeline(output)
    assert t.objects == other.objects
    np.testing.assert_array_equal(t.obj, other.obj)
    for obj_id in [-1, *range(len(t.objects))]:
        np.testing.assert_array_equal(t.object_mask(obj_id), other.object_mask(obj_id))
        for time in [None, 0, t.t1[-1] / 2, t.t1[-1]]:
            np.testing.assert_array_equal(
                t.segments_for_object(obj_id, kinds=[0, 1, 2], t=time),
                other.segments_for_object(obj_id, kinds=[0, 1, 2], t=time),
            )
    for value in [-1, 0, 0.1, *np.linspace(0, t.t1[-1], 21), t.t1[-1] + 1]:
        np.testing.assert_allclose(t.nozzle_at(value)[0], other.nozzle_at(value)[0])
        np.testing.assert_allclose(t.velocity_at(value), other.velocity_at(value))
        assert t.state_at(value) == other.state_at(value)
        np.testing.assert_array_equal(t.extruded_mask(value), other.extruded_mask(value))
        assert t.partial(value) == other.partial(value)
    for layer in range(len(t.layer_z)):
        assert t.layer_range(layer) == other.layer_range(layer)
    np.testing.assert_array_equal(
        t.segments_for_layers(0, 2, kinds=[1, 2, 6]),
        other.segments_for_layers(0, 2, kinds=[1, 2, 6]),
    )
    for key, dtype in {
        "p0": "float32",
        "p1": "float32",
        "e": "float32",
        "width": "float32",
        "height": "float32",
        "t0": "float64",
        "t1": "float64",
        "kind": "uint8",
        "layer": "int32",
        "layer_z": "float32",
        "layer_t0": "float64",
    }.items():
        assert getattr(other, key).dtype == np.dtype(dtype)


