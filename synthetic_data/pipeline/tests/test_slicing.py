@pytest.fixture
def fake_orca(tmp_path, monkeypatch):
    monkeypatch.setattr(slicing, 'GCODE_CACHE', tmp_path / 'gcode')
    monkeypatch.setattr(slicing, 'slicer_version', lambda: 'OrcaSlicer 2.4.2')
    calls = []
    def execute(command, work, timeout):
        calls.append(command)
        (work / 'result.json').write_text(json.dumps({'return_code': 0, 'error_string': 'Success.'}))
        (work / 'plate_1.gcode').write_text(GCODE)
    monkeypatch.setattr(slicing, '_execute', execute)
    return calls


def test_slice_cache_identity_and_pool(entry, fake_orca):
    path = slicing.slice_model(entry, 'prusa_mk4', {})
    assert path.name == 'model.gcode'
    assert slicing.slice_model(entry, 'prusa_mk4', {}) == path
    assert len(fake_orca) == 1
    meta = json.loads(path.with_name('slice.json').read_text())
    assert meta['success'] and meta['estimated_print_time_s'] == 3723
    assert all(meta['comment_markers'].values())
    assert meta['plate_center_mm'] == [125, 105]
    assert '--branch=stable' in fake_orca[0]
    assert '--filesystem=/mnt/Primary' in fake_orca[0]
    assert '--clone-objects' in fake_orca[0]
    assert '--scale' not in fake_orca[0]
    assert trimesh.load_mesh(path.with_name('input.stl')).extents.tolist() == [10, 10, 5]
    process = json.loads(path.with_name('process.json').read_text())
    assert process['enable_arc_fitting'] == '0'
    assert len(slicing.pool('prusa_mk4')) == 1
    other = slicing.slice_model(entry, 'prusa_mk4', {'infill_pattern': 'gyroid'})
    assert other != path
    assert len(slicing.pool('prusa_mk4')) == 2
    trimesh.creation.box([9, 10, 5]).export(entry['stl'])
    assert slicing.slice_model(entry, 'prusa_mk4', {}) != path


def test_failure_is_recorded_and_retried(entry, fake_orca, monkeypatch):
    def fail(command, work, timeout):
        (work / 'slicer.log').write_text('test failure')
        raise TimeoutError('timed out')
    monkeypatch.setattr(slicing, '_execute', fail)
    with pytest.raises(RuntimeError, match='timed out'):
        slicing.slice_model(entry, 'voron24_300', {})
    assert not slicing.pool('voron24_300')
    records = [json.loads(line) for line in (slicing.GCODE_CACHE / 'failed.jsonl').read_text().splitlines()]
    assert len(records) == 1 and not records[0]['success']
    def succeed(command, work, timeout):
        (work / 'model.gcode').write_text(GCODE)
        (work / 'result.json').write_text(json.dumps({'return_code': 0}))
    monkeypatch.setattr(slicing, '_execute', succeed)
    assert slicing.slice_model(entry, 'voron24_300', {}).is_file()


