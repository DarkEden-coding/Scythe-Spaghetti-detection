@pytest.mark.parametrize('settings', [
    {'layer_height': .4}, {'infill_density': 15}, {'copies': 1.5}, {'copies': True},
    {'scale': float('nan')}, {'supports': 'false'}, {'wall_loops': 9}, {'infill_pattern': 'unknown'},
    {'mystery': 1},
])
def test_invalid_settings(settings):
    with pytest.raises(ValueError):
        slicing.normalize_settings(settings)


def test_sample_settings_fit_all_plates(entry):
    entry['bbox_mm'] = [90, 70, 120]
    for p in slicing.PROFILES:
        for seed in range(50):
            settings = slicing.sample_settings(entry, p, random.Random(seed))
            assert settings['scale'] * 120 <= 100.001
            assert settings['scale'] * 90 <= min(slicing.PROFILES[p]) - 10
            assert not settings['supports']


def test_flattened_profiles_are_complete():
    for p, bed in slicing.PROFILES.items():
        for kind in ['machine', 'process', 'filament']:
            data = slicing._profile(p, kind)
            assert not data.get('inherits')
            assert data['type'] == kind
        machine = slicing._profile(p, 'machine')
        assert machine['nozzle_diameter'][0] == '0.4'
        xy = [list(map(float, point.split('x'))) for point in machine['printable_area']]
        assert [max(point[i] for point in xy) for i in range(2)] == list(bed)


@pytest.mark.slow
@pytest.mark.skipif(os.environ.get('SCYTHE_TEST_SLICE') != '1', reason='Set SCYTHE_TEST_SLICE=1 for live Flatpak test')
def test_live_orca(tmp_path, monkeypatch):
    # Temporary integration data stays on the data disk, not pytest's /tmp.
    data = slicing.GCODE_CACHE / '_integration'
    data.mkdir(parents=True, exist_ok=True)
    monkeypatch.setattr(slicing, 'GCODE_CACHE', data / 'gcode_cache')
    stl = data / 'cube.stl'
    trimesh.creation.box([10, 10, 5]).export(stl)
    path = slicing.slice_model({'id': 'pytest_cube', 'stl': str(stl), 'license': 'CC0',
                                'bbox_mm': [10, 10, 5]}, 'prusa_mk4', {})
    assert all(slicing.gcode_details(path)['comment_markers'].values())


def test_bambu_aliases_preserve_original_labels_and_moves(tmp_path):
    p = tmp_path / 'model.gcode'
    text = '; CHANGE_LAYER\n; Z_HEIGHT: 0.2\n; LAYER_HEIGHT: 0.2\n; FEATURE: Outer wall\n; LINE_WIDTH: 0.45\nG1 X2 E1\n'
    p.write_text(text)
    slicing.add_comment_aliases(p)
    result = p.read_text()
    assert ';WIDTH:0.45' in result and ';HEIGHT:0.2' in result and ';Z:0.2' in result
    assert all(line in result for line in text.splitlines())
    assert all(slicing.gcode_details(p)['comment_markers'].values())


